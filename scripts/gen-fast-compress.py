#!/usr/bin/env python3
"""Writes the body of the fast SHA-256 block function (`_compress` in
src/lib.bats): the 64 rounds of FIPS 180-4, section 6.2.2 written out one
after another, with the round constants as literals and the message
schedule as named words, so a block needs no table, no schedule array, no
loop and no eight-word tuple.

  scripts/gen-fast-compress.py          rewrite the generated region of src/lib.bats
  scripts/gen-fast-compress.py --check  fail when the region is not what this writes

The region is between the two marker lines below. Nothing here is proved
(the proved SHA-256 is `proved_hash`); the fast code is tested against it
and against hashlib (tests/dynamic/proved, vectors).
"""
import re, sys, os

BEGIN = "(* begin generated by scripts/gen-fast-compress.py *)"
END = "(* end generated by scripts/gen-fast-compress.py *)"

# FIPS 180-4, section 4.2.2
K = """428a2f98 71374491 b5c0fbcf e9b5dba5 3956c25b 59f111f1 923f82a4 ab1c5ed5
d807aa98 12835b01 243185be 550c7dc3 72be5d74 80deb1fe 9bdc06a7 c19bf174
e49b69c1 efbe4786 0fc19dc6 240ca1cc 2de92c6f 4a7484aa 5cb0a9dc 76f988da
983e5152 a831c66d b00327c8 bf597fc7 c6e00bf3 d5a79147 06ca6351 14292967
27b70a85 2e1b2138 4d2c6dfc 53380d13 650a7354 766a0abb 81c2c92e 92722c85
a2bfe8a1 a81a664b c24b8b70 c76c51a3 d192e819 d6990624 f40e3585 106aa070
19a4c116 1e376c08 2748774c 34b0bcb5 391c0cb3 4ed8aa4a 5b9cca4f 682e6ff3
748f82ee 78a5636f 84c87814 8cc70208 90befffa a4506ceb bef9a3f7 c67178f2""".split()
assert len(K) == 64


def generate():
    out = []
    out.append("  (* the 16 words of the block *)")
    for t in range(16):
        out.append("  val w%d = _word(data, bo + %d)" % (t, 4 * t))
    out.append("  (* the chaining value *)")
    for i in range(8):
        out.append("  val h%d = $A.get<uint>(h, %d)" % (i, i))
    # the working variables a..h, by the names of their values
    s = ["h%d" % i for i in range(8)]
    for t in range(64):
        if t >= 16:
            out.append("  val w%d = _schedule(w%d, w%d, w%d, w%d)" % (t, t - 2, t - 7, t - 15, t - 16))
        a, b, c, d, e, f, g, hh = s
        out.append("  val @(e%d, a%d) = _round(%s, %s, %s, %s, %s, %s, %s, %s, 0x%su + w%d)"
                   % (t, t, a, b, c, d, e, f, g, hh, K[t], t))
        s = ["a%d" % t, a, b, c, "e%d" % t, e, f, g]
    for i in range(8):
        out.append("  val () = $A.set<uint>(h, %d, h%d + %s)" % (i, i, s[i]))
    return "\n".join(out) + "\n"


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "lib.bats")
    text = open(path).read()
    i = text.index(BEGIN) + len(BEGIN) + 1
    j = text.index(END)
    new = text[:i] + generate() + text[j:]
    if "--check" in sys.argv:
        if new != text:
            sys.exit("the generated region of src/lib.bats is not what scripts/gen-fast-compress.py writes")
        return
    open(path, "w").write(new)


main()
