#!/usr/bin/env python3
"""Writes the proofs that the primes in the constants' guards are the first
64 primes (sha256#78, keyword: nth-prime): for each t, the private proof
`_nth_prime_<t>` of NTH_PRIME(t, p_t), and the bodies of `sha256_k_prime` and
`sha256_iv_primes` (src/lib.bats).

  scripts/gen-primes.py          rewrite the generated region of src/lib.bats
  scripts/gen-primes.py --check  fail when the region is not what this writes

Only the text is generated, from the definition (trial division, integer
roots): nothing here is believed. The compiler checks every witness it
writes (n = d*q + m with 0 < m < d for each divisor up to the root, and
d*q for each number between two consecutive primes), so a wrong witness is a
type error, not a wrong proof. The relations are in src/lib.bats.
"""
import os
import sys

BEGIN = "(* begin generated by scripts/gen-primes.py *)"
END = "(* end generated by scripts/gen-primes.py *)"
BEGIN_R = "(* begin generated by scripts/gen-primes.py, relations *)"
END_R = "(* end generated by scripts/gen-primes.py, relations *)"


def primes(count):
    found = []
    n = 2
    while len(found) < count:
        if all(n % q for q in found if q * q <= n):
            found.append(n)
        n += 1
    return found


def isqrt(n):
    lo, hi = 0, 1
    while hi * hi <= n:
        hi *= 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if mid * mid <= n:
            lo = mid
        else:
            hi = mid
    return lo


def icbrt(n):
    lo, hi = 0, 1
    while hi ** 3 <= n:
        hi *= 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if mid ** 3 <= n:
            lo = mid
        else:
            hi = mid
    return lo


def halves(x):
    low_32 = x & 0xffffffff
    return low_32 >> 16, low_32 & 0xffff


def prime_proof(p):
    """PRIME(p): the divisions of p by each e from 2 to its root, each with a remainder above 0"""
    r = isqrt(p)
    text = "NO_DIVISOR_none()"
    for e in range(r, 1, -1):
        assert p % e != 0
        text = "NO_DIVISOR_step{%d, %d}(%s)" % (p // e, p % e, text)
    return "PRIME_mk{%d}(%s)" % (r, text)


def nonprimes_proof(a, b):
    """NONPRIMES(a, b): the factorisation of each n with a < n < b, by its least factor"""
    text = "NONPRIMES_none()"
    for n in range(b - 1, a, -1):
        d = next(e for e in range(2, n) if n % e == 0)
        text = "NONPRIMES_next(COMPOSITE_mk{%d, %d}(), %s)" % (d, n // d, text)
    return text


def generate():
    ps = primes(64)
    out = []
    out.append("prfn _nth_prime_0 (): NTH_PRIME(0, 2) = NTH_PRIME_first(%s)" % prime_proof(2))
    for t in range(1, 64):
        out.append("")
        p, q = ps[t - 1], ps[t]
        out.append("prfn _nth_prime_%d (): NTH_PRIME(%d, %d) =" % (t, t, q))
        out.append("  NTH_PRIME_next(_nth_prime_%d(), %s," % (t - 1, nonprimes_proof(p, q)))
        out.append("    %s)" % prime_proof(q))
    out.append("")
    out.append("implement sha256_k_nth_w32 {t} (t) =")
    for t in range(64):
        x = icbrt(ps[t] << 96)
        h, l = halves(x)
        branch = ("    (SHA256_K_%d(), SHA256_K_PRIMED_%d(_nth_prime_%d()) | $AR.word32_pack_inline(0x%02x, 0x%02x, 0x%02x, 0x%02x))"
                  % (t, t, t, h >> 8, h & 255, l >> 8, l & 255))
        if t < 63:
            out.append("  if $AR.eq_g1(t, %d) then" % t)
            out.append(branch)
            out.append("  else")
        else:
            out.append(branch)
    out.append("")
    ivs = []
    for j in range(8):
        x = isqrt(ps[j] << 64)
        h, l = halves(x)
        ivs.append((j, x >> 32, ps[j], h, l))
    out.append("implement sha256_iv_nth_w32 () =")
    out.append("  (SHA256_IV_mk(), SHA256_IV_PRIMED_mk(" + ", ".join("_nth_prime_%d()" % j for j in range(8)) + ") |")
    out.append("   @(" + ", ".join("$AR.word32_pack_inline(0x%02x, 0x%02x, 0x%02x, 0x%02x)" % (h >> 8, h & 255, l >> 8, l & 255) for j, i, p, h, l in ivs) + "))")
    return "\n".join(out) + "\n"


def relations(text):
    """the constructors of SHA256_K_PRIMED and SHA256_IV_PRIMED: those of SHA256_K and SHA256_IV, guard for guard,
    each with the proof NTH_PRIME of its own p; the old guards are read from src/lib.bats and must be the
    definition's (the integer part i of the root of the (t+1)-th prime p)"""
    ps = primes(64)
    out = ["#pub dataprop SHA256_K_PRIMED(int, int, int, int) ="]
    for t in range(64):
        i = icbrt(ps[t] << 96) >> 32
        old = ("  | {high,low:nat | high < 65536; low < 65536; cube_fraction_le(%d, high, low, %d); cube_fraction_gt(%d, high, low, %d)} SHA256_K_%d(%d, high, low)"
               % (i, ps[t], i, ps[t], t, t))
        if old not in text.split("\n"):
            sys.exit("the constructor SHA256_K_%d in src/lib.bats is not the definition's (i = %d, p = %d)" % (t, i, ps[t]))
        out.append(old.replace("SHA256_K_%d(%d, high, low)" % (t, t), "SHA256_K_PRIMED_%d(%d, %d, high, low) of NTH_PRIME(%d, %d)" % (t, t, ps[t], t, ps[t])))
    out.append("")
    guards = []
    for j in range(8):
        i = isqrt(ps[j] << 64) >> 32
        guards.append("sqrt_fraction32_le(%d, h%d_high, h%d_low, %d); sqrt_fraction32_gt(%d, h%d_high, h%d_low, %d)" % (i, j, j, ps[j], i, j, j, ps[j]))
    names = ",".join("h%d_high,h%d_low" % (j, j) for j in range(8))
    bounds = "; ".join("h%d_high < 65536; h%d_low < 65536" % (j, j) for j in range(8))
    guard_line = "     " + "; ".join(guards) + "}"
    if guard_line not in text.split("\n") or ("  | {%s:nat | %s;" % (names, bounds)) not in text:
        sys.exit("the constructor SHA256_IV_mk in src/lib.bats is not the definition's")
    words = ", ".join("w32(h%d_high, h%d_low)" % (j, j) for j in range(8))
    out.append("#pub dataprop SHA256_IV_PRIMED(eight_words) =")
    out.append("  | {%s:nat | %s;" % (names, bounds))
    out.append(guard_line)
    out.append("    SHA256_IV_PRIMED_mk(eight(%s)) of (%s)" % (words, ", ".join("NTH_PRIME(%d, %d)" % (j, ps[j]) for j in range(8))))
    return "\n".join(out) + "\n"


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "lib.bats")
    text = open(path).read()
    i = text.index(BEGIN_R) + len(BEGIN_R) + 1
    j = text.index(END_R)
    new = text[:i] + relations(text) + text[j:]
    i = new.index(BEGIN) + len(BEGIN) + 1
    j = new.index(END)
    new = new[:i] + generate() + new[j:]
    if "--check" in sys.argv:
        if new != text:
            sys.exit("the generated regions of src/lib.bats are not what scripts/gen-primes.py writes")
        return
    open(path, "w").write(new)


main()
