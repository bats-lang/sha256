#!/usr/bin/env python3
"""Writes the proofs that the primes in the constants' guards are the first
64 primes (sha256#78, keyword: nth-prime): for each t, the private proof
`_nth_prime_<t>` of NTH_PRIME(t, p_t), and the bodies of `sha256_k_prime` and
`sha256_iv_primes` (src/lib.bats).

  scripts/gen-primes.py          rewrite the generated region of src/lib.bats
  scripts/gen-primes.py --check  fail when the region is not what this writes

Only the text is generated, from the definition (trial division, integer
roots): nothing here is believed. The compiler checks every witness it
writes (n = d*q + m with 0 < m < d for each divisor up to the root, and
d*q for each number between two consecutive primes), so a wrong witness is a
type error, not a wrong proof. The relations are in src/lib.bats.
"""
import os
import sys

BEGIN = "(* begin generated by scripts/gen-primes.py *)"
END = "(* end generated by scripts/gen-primes.py *)"


def primes(count):
    found = []
    n = 2
    while len(found) < count:
        if all(n % q for q in found if q * q <= n):
            found.append(n)
        n += 1
    return found


def isqrt(n):
    lo, hi = 0, 1
    while hi * hi <= n:
        hi *= 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if mid * mid <= n:
            lo = mid
        else:
            hi = mid
    return lo


def icbrt(n):
    lo, hi = 0, 1
    while hi ** 3 <= n:
        hi *= 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if mid ** 3 <= n:
            lo = mid
        else:
            hi = mid
    return lo


def halves(x):
    low_32 = x & 0xffffffff
    return low_32 >> 16, low_32 & 0xffff


def prime_proof(p):
    """PRIME(p): the divisions of p by each e from 2 to its root, each with a remainder above 0"""
    r = isqrt(p)
    text = "NO_DIVISOR_none()"
    for e in range(r, 1, -1):
        assert p % e != 0
        text = "NO_DIVISOR_step{%d, %d}(%s)" % (p // e, p % e, text)
    return "PRIME_mk{%d}(%s)" % (r, text)


def nonprimes_proof(a, b):
    """NONPRIMES(a, b): the factorisation of each n with a < n < b, by its least factor"""
    text = "NONPRIMES_none()"
    for n in range(b - 1, a, -1):
        d = next(e for e in range(2, n) if n % e == 0)
        text = "NONPRIMES_next(COMPOSITE_mk{%d, %d}(), %s)" % (d, n // d, text)
    return text


def generate():
    ps = primes(64)
    out = []
    out.append("prfn _nth_prime_0 (): NTH_PRIME(0, 2) = NTH_PRIME_first(%s)" % prime_proof(2))
    for t in range(1, 64):
        out.append("")
        p, q = ps[t - 1], ps[t]
        out.append("prfn _nth_prime_%d (): NTH_PRIME(%d, %d) =" % (t, t, q))
        out.append("  NTH_PRIME_next(_nth_prime_%d(), %s," % (t - 1, nonprimes_proof(p, q)))
        out.append("    %s)" % prime_proof(q))
    out.append("")
    out.append("implement sha256_k_nth_w32 {t} (t) =")
    for t in range(64):
        x = icbrt(ps[t] << 96)
        h, l = halves(x)
        branch = ("    (SHA256_K_%d(), SHA256_K_OF_PRIME_mk{%d}{%d, %d, 0x%04x, 0x%04x}(_nth_prime_%d()) | $AR.word32_pack_inline(0x%02x, 0x%02x, 0x%02x, 0x%02x))"
                  % (t, x >> 32, t, ps[t], h, l, t, h >> 8, h & 255, l >> 8, l & 255))
        if t < 63:
            out.append("  if $AR.eq_g1(t, %d) then" % t)
            out.append(branch)
            out.append("  else")
        else:
            out.append(branch)
    out.append("")
    ivs = []
    for j in range(8):
        x = isqrt(ps[j] << 64)
        h, l = halves(x)
        ivs.append((j, x >> 32, ps[j], h, l))
    out.append("implement sha256_iv_nth_w32 () =")
    out.append("  (SHA256_IV_mk(),")
    out.append(",\n".join("   SHA256_IV_OF_PRIME_mk{%d}{%d, %d, 0x%04x, 0x%04x}(_nth_prime_%d())" % (i, j, p, h, l, j) for j, i, p, h, l in ivs) + " |")
    out.append("   @(" + ", ".join("$AR.word32_pack_inline(0x%02x, 0x%02x, 0x%02x, 0x%02x)" % (h >> 8, h & 255, l >> 8, l & 255) for j, i, p, h, l in ivs) + "))")
    return "\n".join(out) + "\n"


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "lib.bats")
    text = open(path).read()
    i = text.index(BEGIN) + len(BEGIN) + 1
    j = text.index(END)
    new = text[:i] + generate() + text[j:]
    if "--check" in sys.argv:
        if new != text:
            sys.exit("the generated region of src/lib.bats is not what scripts/gen-primes.py writes")
        return
    open(path, "w").write(new)


main()
